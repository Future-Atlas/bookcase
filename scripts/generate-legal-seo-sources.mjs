import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sources = {
  privacy: "lib/screens/privacy_policy_screen.dart",
  terms: "lib/screens/terms_screen.dart",
  "community-guidelines": "lib/screens/community_guidelines_screen.dart",
  "infringement-policy": "lib/screens/infringement_policy_screen.dart",
  "external-transmission": "lib/screens/external_transmission_screen.dart",
};

const contents = Object.fromEntries(
  Object.entries(sources).map(([key, relativePath]) => [
    key,
    fs.readFileSync(path.join(root, relativePath), "utf8"),
  ]),
);

const output = `// Generated by scripts/generate-legal-seo-sources.mjs.
// Do not edit directly; edit the corresponding Flutter legal screen instead.
const SOURCES = ${JSON.stringify(contents, null, 2)};

module.exports = { SOURCES };
`;

fs.writeFileSync(path.join(root, "api/_legal_sources.js"), output, "utf8");
