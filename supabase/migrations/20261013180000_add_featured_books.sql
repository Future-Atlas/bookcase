-- Administrator-curated books shown on the Sharemarium home page.
-- Book metadata is stored as a snapshot because the catalog itself is external.

CREATE TABLE IF NOT EXISTS public.featured_books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id TEXT NOT NULL UNIQUE,
    book_title TEXT NOT NULL,
    book_author TEXT NOT NULL DEFAULT '',
    book_publisher TEXT NOT NULL DEFAULT '',
    book_cover_url TEXT NOT NULL DEFAULT '',
    book_description TEXT NOT NULL DEFAULT '',
    related_screen_titles TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    priority INTEGER NOT NULL DEFAULT 0,
    starts_at TIMESTAMP WITH TIME ZONE,
    ends_at TIMESTAMP WITH TIME ZONE,
    created_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc', now()),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc', now()),
    CHECK (char_length(btrim(book_id)) BETWEEN 10 AND 32),
    CHECK (char_length(btrim(book_title)) BETWEEN 1 AND 500),
    CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);

CREATE INDEX IF NOT EXISTS featured_books_public_order_idx
    ON public.featured_books (priority ASC, created_at DESC);

ALTER TABLE public.featured_books ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anyone can read active featured books"
    ON public.featured_books;
CREATE POLICY "Anyone can read active featured books"
    ON public.featured_books FOR SELECT
    USING (
        (starts_at IS NULL OR starts_at <= timezone('utc', now()))
        AND (ends_at IS NULL OR ends_at > timezone('utc', now()))
    );

DROP POLICY IF EXISTS "Administrators can read all featured books"
    ON public.featured_books;
CREATE POLICY "Administrators can read all featured books"
    ON public.featured_books FOR SELECT TO authenticated
    USING (public.is_current_user_admin());

DROP POLICY IF EXISTS "Administrators can manage featured books"
    ON public.featured_books;
CREATE POLICY "Administrators can manage featured books"
    ON public.featured_books FOR ALL TO authenticated
    USING (public.is_current_user_admin())
    WITH CHECK (public.is_current_user_admin());

GRANT SELECT ON public.featured_books TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.featured_books TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.featured_books_id_seq TO authenticated;

COMMENT ON TABLE public.featured_books IS
    'Administrator-curated books displayed as featured editorial links.';
COMMENT ON COLUMN public.featured_books.related_screen_titles IS
    'Verified film or screen adaptation titles only; never generated for keyword stuffing.';
