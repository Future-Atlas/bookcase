CREATE OR REPLACE FUNCTION public.require_private_data_operator(
    p_password TEXT,
    p_reason TEXT,
    p_request_reference TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF auth.uid() IS NULL OR NOT public.is_current_user_admin() THEN
        RAISE EXCEPTION 'Administrator access required' USING ERRCODE = '42501';
    END IF;
    IF char_length(btrim(p_reason)) NOT BETWEEN 10 AND 500
       OR char_length(btrim(p_request_reference)) NOT BETWEEN 1 AND 100 THEN
        RAISE EXCEPTION 'Reason and request reference are required'
            USING ERRCODE = '23514';
    END IF;
    IF NOT public.verify_privacy_password(p_password) THEN
        RAISE EXCEPTION 'Additional password verification failed'
            USING ERRCODE = '28P01';
    END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.require_private_data_operator(TEXT, TEXT, TEXT)
    FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.resolve_private_data_target(
    p_target_identifier TEXT
)
RETURNS UUID
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    normalized_identifier TEXT := lower(ltrim(btrim(p_target_identifier), '@'));
    resolved_profile UUID;
BEGIN
    IF normalized_identifier ~
       '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' THEN
        SELECT id INTO resolved_profile
        FROM public.profiles
        WHERE id = normalized_identifier::UUID;
    ELSE
        SELECT id INTO resolved_profile
        FROM public.profiles
        WHERE lower(user_id) = normalized_identifier;
    END IF;

    IF resolved_profile IS NULL THEN
        RAISE EXCEPTION 'Target account not found' USING ERRCODE = 'P0002';
    END IF;
    RETURN resolved_profile;
END;
$$;

REVOKE ALL ON FUNCTION public.resolve_private_data_target(TEXT)
    FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.admin_read_private_account_details(
    p_target_identifier TEXT,
    p_admin_password TEXT,
    p_reason TEXT,
    p_request_reference TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
    target_profile UUID;
    details public.account_details%ROWTYPE;
    target_email TEXT;
    target_user_id TEXT;
    session_value UUID;
BEGIN
    PERFORM public.require_private_data_operator(
        p_admin_password,
        p_reason,
        p_request_reference
    );
    target_profile := public.resolve_private_data_target(p_target_identifier);

    SELECT * INTO STRICT details
    FROM public.account_details
    WHERE profile_id = target_profile;

    SELECT users.email, profiles.user_id
    INTO target_email, target_user_id
    FROM auth.users AS users
    JOIN public.profiles AS profiles ON profiles.id = users.id
    WHERE users.id = target_profile;

    BEGIN
        session_value := nullif(auth.jwt() ->> 'session_id', '')::UUID;
    EXCEPTION WHEN invalid_text_representation THEN
        session_value := NULL;
    END;

    INSERT INTO public.private_data_admin_audit (
        actor_profile_id,
        target_profile_id,
        action,
        reason,
        request_reference,
        session_id
    ) VALUES (
        auth.uid(),
        target_profile,
        'view',
        btrim(p_reason),
        btrim(p_request_reference),
        session_value
    );

    RETURN jsonb_build_object(
        'profile_id', details.profile_id,
        'user_id', target_user_id,
        'family_name', details.family_name,
        'given_name', details.given_name,
        'birth_date', details.birth_date,
        'phone_number', details.phone_number,
        'gender', details.gender,
        'email', target_email
    );
END;
$$;

REVOKE ALL ON FUNCTION public.admin_read_private_account_details(
    TEXT, TEXT, TEXT, TEXT
) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_read_private_account_details(
    TEXT, TEXT, TEXT, TEXT
) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_update_private_account_details(
    p_target_identifier TEXT,
    p_admin_password TEXT,
    p_reason TEXT,
    p_request_reference TEXT,
    p_family_name TEXT,
    p_given_name TEXT,
    p_birth_date DATE,
    p_phone_number TEXT,
    p_gender TEXT
)
RETURNS TEXT[]
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    target_profile UUID;
    current_details public.account_details%ROWTYPE;
    normalized_family_name TEXT := btrim(p_family_name);
    normalized_given_name TEXT := btrim(p_given_name);
    normalized_phone TEXT := regexp_replace(p_phone_number, '[^0-9+]', '', 'g');
    normalized_gender TEXT := lower(btrim(p_gender));
    changed TEXT[] := ARRAY[]::TEXT[];
    session_value UUID;
BEGIN
    PERFORM public.require_private_data_operator(
        p_admin_password,
        p_reason,
        p_request_reference
    );
    target_profile := public.resolve_private_data_target(p_target_identifier);

    IF char_length(normalized_family_name) NOT BETWEEN 1 AND 50
       OR char_length(normalized_given_name) NOT BETWEEN 1 AND 50
       OR char_length(normalized_family_name || ' ' || normalized_given_name) > 100
       OR p_birth_date < DATE '1900-01-01'
       OR p_birth_date > CURRENT_DATE
       OR normalized_phone !~ '^\+?[0-9]{7,15}$'
       OR normalized_gender NOT IN ('female', 'male', 'undisclosed') THEN
        RAISE EXCEPTION 'Invalid private account data' USING ERRCODE = '23514';
    END IF;

    SELECT * INTO STRICT current_details
    FROM public.account_details
    WHERE profile_id = target_profile
    FOR UPDATE;

    IF current_details.family_name IS DISTINCT FROM normalized_family_name THEN
        changed := array_append(changed, 'family_name');
    END IF;
    IF current_details.given_name IS DISTINCT FROM normalized_given_name THEN
        changed := array_append(changed, 'given_name');
    END IF;
    IF current_details.birth_date IS DISTINCT FROM p_birth_date THEN
        changed := array_append(changed, 'birth_date');
    END IF;
    IF current_details.phone_number IS DISTINCT FROM normalized_phone THEN
        changed := array_append(changed, 'phone_number');
    END IF;
    IF current_details.gender IS DISTINCT FROM normalized_gender THEN
        changed := array_append(changed, 'gender');
    END IF;

    IF cardinality(changed) = 0 THEN
        RAISE EXCEPTION 'No private account data changed' USING ERRCODE = '22023';
    END IF;

    UPDATE public.account_details
    SET family_name = normalized_family_name,
        given_name = normalized_given_name,
        full_name = normalized_family_name || ' ' || normalized_given_name,
        birth_date = p_birth_date,
        phone_number = normalized_phone,
        phone_verified_at = CASE
            WHEN phone_number = normalized_phone THEN phone_verified_at
            ELSE NULL
        END,
        gender = normalized_gender,
        updated_at = timezone('utc'::text, now())
    WHERE profile_id = target_profile;

    BEGIN
        session_value := nullif(auth.jwt() ->> 'session_id', '')::UUID;
    EXCEPTION WHEN invalid_text_representation THEN
        session_value := NULL;
    END;

    INSERT INTO public.private_data_admin_audit (
        actor_profile_id,
        target_profile_id,
        action,
        changed_fields,
        reason,
        request_reference,
        session_id
    ) VALUES (
        auth.uid(),
        target_profile,
        'update',
        changed,
        btrim(p_reason),
        btrim(p_request_reference),
        session_value
    );

    RETURN changed;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_update_private_account_details(
    TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, DATE, TEXT, TEXT
) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_update_private_account_details(
    TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, DATE, TEXT, TEXT
) TO authenticated;
