CREATE OR REPLACE FUNCTION public.update_own_private_contact_details(
    p_password TEXT,
    p_gender TEXT,
    p_phone_number TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
    current_profile_id UUID := auth.uid();
    normalized_gender TEXT := lower(btrim(p_gender));
    normalized_phone TEXT := regexp_replace(p_phone_number, '[^0-9+]', '', 'g');
BEGIN
    IF current_profile_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;
    IF NOT public.verify_privacy_password(p_password) THEN
        RETURN FALSE;
    END IF;
    IF normalized_gender NOT IN ('female', 'male', 'undisclosed')
       OR normalized_phone !~ '^\+?[0-9]{7,15}$' THEN
        RAISE EXCEPTION 'Invalid private contact data' USING ERRCODE = '23514';
    END IF;

    UPDATE public.account_details
    SET gender = normalized_gender,
        phone_number = normalized_phone,
        phone_verified_at = CASE
            WHEN phone_number = normalized_phone THEN phone_verified_at
            ELSE NULL
        END,
        updated_at = timezone('utc'::text, now())
    WHERE profile_id = current_profile_id;

    RETURN FOUND;
END;
$$;

REVOKE ALL ON FUNCTION public.update_own_private_contact_details(TEXT, TEXT, TEXT)
    FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.update_own_private_contact_details(TEXT, TEXT, TEXT)
    TO authenticated;

