-- Make private registration data immutable to ordinary browser updates while
-- retaining a narrow, audited correction path for the account owner and
-- authorized Sharemarium operators.

CREATE TABLE IF NOT EXISTS public.private_data_admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_profile_id UUID NOT NULL,
    target_profile_id UUID NOT NULL,
    action TEXT NOT NULL CHECK (action IN ('view', 'update')),
    changed_fields TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    reason TEXT NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 10 AND 500),
    request_reference TEXT NOT NULL CHECK (
        char_length(btrim(request_reference)) BETWEEN 1 AND 100
    ),
    session_id UUID,
    created_at TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.private_data_admin_audit IS
    'Append-only evidence that an authorized operator viewed or corrected private account data. The audit deliberately does not duplicate the private values.';

ALTER TABLE public.private_data_admin_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.private_data_admin_audit
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.private_data_admin_audit_id_seq
    FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.prevent_private_data_admin_audit_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    RAISE EXCEPTION 'Private-data audit records are append-only'
        USING ERRCODE = '42501';
END;
$$;

REVOKE ALL ON FUNCTION public.prevent_private_data_admin_audit_mutation()
    FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS private_data_admin_audit_immutable
    ON public.private_data_admin_audit;
CREATE TRIGGER private_data_admin_audit_immutable
BEFORE UPDATE OR DELETE ON public.private_data_admin_audit
FOR EACH ROW EXECUTE FUNCTION public.prevent_private_data_admin_audit_mutation();

