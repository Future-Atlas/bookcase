-- Require a verified TOTP factor for Sharemarium sessions and for privacy-
-- password recovery. Recovery verification is performed by the
-- totp-recovery Edge Function so the application-level five-attempt limit
-- cannot be bypassed by calling a browser RPC directly.

ALTER TABLE public.privacy_password_recovery_requests
    ADD COLUMN IF NOT EXISTS totp_verified_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE IF NOT EXISTS public.totp_verification_limits (
    profile_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    purpose TEXT NOT NULL CHECK (purpose IN ('login', 'privacy_recovery')),
    failed_attempts SMALLINT NOT NULL DEFAULT 0 CHECK (failed_attempts BETWEEN 0 AND 5),
    locked_until TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT timezone('utc'::text, now()),
    PRIMARY KEY (profile_id, purpose)
);

CREATE TABLE IF NOT EXISTS public.totp_recovery_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_profile_id UUID NOT NULL,
    target_profile_id UUID NOT NULL,
    action TEXT NOT NULL CHECK (action IN ('self_reenroll', 'admin_reset')),
    outcome TEXT NOT NULL CHECK (outcome IN ('authorized', 'completed', 'failed')),
    reason TEXT NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 10 AND 500),
    request_reference TEXT NOT NULL CHECK (
        char_length(btrim(request_reference)) BETWEEN 1 AND 100
    ),
    session_id UUID,
    created_at TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.totp_recovery_audit IS
    'Append-only evidence of TOTP factor resets. Secrets and six-digit codes are deliberately excluded.';

ALTER TABLE public.totp_verification_limits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.totp_recovery_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.totp_verification_limits, public.totp_recovery_audit
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.totp_recovery_audit_id_seq
    FROM PUBLIC, anon, authenticated;

