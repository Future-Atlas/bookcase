CREATE OR REPLACE FUNCTION public.begin_privacy_password_recovery()
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    current_provider TEXT := auth.jwt() -> 'app_metadata' ->> 'provider';
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;
    IF current_provider NOT IN ('google', 'twitter', 'x') THEN
        RAISE EXCEPTION 'Unsupported recovery provider' USING ERRCODE = '22023';
    END IF;

    INSERT INTO public.privacy_password_recovery_requests (
        profile_id, provider, requested_at, totp_verified_at
    ) VALUES (
        auth.uid(), current_provider, timezone('utc'::text, now()), NULL
    )
    ON CONFLICT (profile_id) DO UPDATE
    SET provider = EXCLUDED.provider,
        requested_at = EXCLUDED.requested_at,
        totp_verified_at = NULL;

    INSERT INTO public.totp_verification_limits (
        profile_id, purpose, failed_attempts, locked_until
    ) VALUES (auth.uid(), 'privacy_recovery', 0, NULL)
    ON CONFLICT (profile_id, purpose) DO UPDATE
    SET failed_attempts = CASE
            WHEN public.totp_verification_limits.locked_until <= timezone('utc'::text, now())
                THEN 0
            ELSE public.totp_verification_limits.failed_attempts
        END,
        locked_until = CASE
            WHEN public.totp_verification_limits.locked_until <= timezone('utc'::text, now())
                THEN NULL
            ELSE public.totp_verification_limits.locked_until
        END,
        updated_at = timezone('utc'::text, now());
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_privacy_password_recovery_oauth()
RETURNS BOOLEAN
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    recovery public.privacy_password_recovery_requests%ROWTYPE;
    has_recent_oauth BOOLEAN;
BEGIN
    IF auth.uid() IS NULL THEN RETURN FALSE; END IF;
    SELECT * INTO recovery
    FROM public.privacy_password_recovery_requests
    WHERE profile_id = auth.uid()
      AND requested_at >= timezone('utc'::text, now()) - interval '15 minutes';
    IF NOT FOUND
       OR recovery.provider NOT IN ('google', 'twitter', 'x')
       OR (auth.jwt() -> 'app_metadata' ->> 'provider') IS DISTINCT FROM recovery.provider THEN
        RETURN FALSE;
    END IF;
    SELECT EXISTS (
        SELECT 1
        FROM jsonb_array_elements(COALESCE(auth.jwt() -> 'amr', '[]'::jsonb)) AS entry
        WHERE entry ->> 'method' = 'oauth'
          AND to_timestamp((entry ->> 'timestamp')::double precision)
              >= recovery.requested_at - interval '5 seconds'
    ) INTO has_recent_oauth;
    RETURN has_recent_oauth;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_totp_verification_state(
    p_target_profile UUID,
    p_purpose TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    attempt_count SMALLINT := 0;
    lock_time TIMESTAMP WITH TIME ZONE;
BEGIN
    IF p_purpose NOT IN ('login', 'privacy_recovery') THEN
        RAISE EXCEPTION 'Invalid TOTP purpose' USING ERRCODE = '22023';
    END IF;
    SELECT failed_attempts, locked_until INTO attempt_count, lock_time
    FROM public.totp_verification_limits
    WHERE profile_id = p_target_profile AND purpose = p_purpose;
    attempt_count := COALESCE(attempt_count, 0);
    RETURN jsonb_build_object(
        'failed_attempts', attempt_count,
        'remaining_attempts', greatest(0, 5 - attempt_count),
        'locked_until', lock_time,
        'locked', COALESCE(lock_time > timezone('utc'::text, now()), FALSE)
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.record_totp_verification_failure(
    p_target_profile UUID,
    p_purpose TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    row_value public.totp_verification_limits%ROWTYPE;
    next_attempts SMALLINT;
BEGIN
    IF p_purpose NOT IN ('login', 'privacy_recovery') THEN
        RAISE EXCEPTION 'Invalid TOTP purpose' USING ERRCODE = '22023';
    END IF;
    INSERT INTO public.totp_verification_limits (profile_id, purpose)
    VALUES (p_target_profile, p_purpose)
    ON CONFLICT (profile_id, purpose) DO NOTHING;

    SELECT * INTO STRICT row_value
    FROM public.totp_verification_limits
    WHERE profile_id = p_target_profile AND purpose = p_purpose
    FOR UPDATE;
    IF row_value.locked_until > timezone('utc'::text, now()) THEN
        RETURN public.get_totp_verification_state(p_target_profile, p_purpose);
    END IF;

    next_attempts := CASE
        WHEN row_value.locked_until IS NOT NULL THEN 1
        ELSE least(5, row_value.failed_attempts + 1)
    END;
    UPDATE public.totp_verification_limits
    SET failed_attempts = next_attempts,
        locked_until = CASE
            WHEN next_attempts >= 5
                THEN timezone('utc'::text, now()) + interval '24 hours'
            ELSE NULL
        END,
        updated_at = timezone('utc'::text, now())
    WHERE profile_id = p_target_profile AND purpose = p_purpose;
    RETURN public.get_totp_verification_state(p_target_profile, p_purpose);
END;
$$;

CREATE OR REPLACE FUNCTION public.record_totp_verification_success(
    p_target_profile UUID,
    p_purpose TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF p_purpose NOT IN ('login', 'privacy_recovery') THEN
        RAISE EXCEPTION 'Invalid TOTP purpose' USING ERRCODE = '22023';
    END IF;
    INSERT INTO public.totp_verification_limits (
        profile_id, purpose, failed_attempts, locked_until
    ) VALUES (p_target_profile, p_purpose, 0, NULL)
    ON CONFLICT (profile_id, purpose) DO UPDATE
    SET failed_attempts = 0,
        locked_until = NULL,
        updated_at = timezone('utc'::text, now());
    IF p_purpose = 'privacy_recovery' THEN
        UPDATE public.privacy_password_recovery_requests
        SET totp_verified_at = timezone('utc'::text, now())
        WHERE profile_id = p_target_profile
          AND requested_at >= timezone('utc'::text, now()) - interval '15 minutes';
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Recovery request expired' USING ERRCODE = '42501';
        END IF;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.authorize_self_totp_reenrollment(
    p_password TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;
    RETURN public.verify_privacy_password(p_password);
END;
$$;

CREATE OR REPLACE FUNCTION public.authorize_admin_totp_reset(
    p_target_identifier TEXT,
    p_admin_password TEXT,
    p_reason TEXT,
    p_request_reference TEXT
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF COALESCE(auth.jwt() ->> 'aal', '') <> 'aal2' THEN
        RAISE EXCEPTION 'AAL2 authentication required' USING ERRCODE = '42501';
    END IF;
    PERFORM public.require_private_data_operator(
        p_admin_password, p_reason, p_request_reference
    );
    RETURN public.resolve_private_data_target(p_target_identifier);
END;
$$;

CREATE OR REPLACE FUNCTION public.reset_privacy_password_after_reauthentication(
    p_new_password TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
    recovery public.privacy_password_recovery_requests%ROWTYPE;
    has_recent_oauth BOOLEAN;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;
    IF COALESCE(auth.jwt() ->> 'aal', '') <> 'aal2' THEN
        RAISE EXCEPTION 'AAL2 authentication required' USING ERRCODE = '42501';
    END IF;
    IF NOT public.is_valid_privacy_password(p_new_password) THEN
        RAISE EXCEPTION 'Invalid privacy password' USING ERRCODE = '23514';
    END IF;
    SELECT * INTO recovery
    FROM public.privacy_password_recovery_requests
    WHERE profile_id = auth.uid()
      AND requested_at >= timezone('utc'::text, now()) - interval '15 minutes'
      AND totp_verified_at >= timezone('utc'::text, now()) - interval '15 minutes'
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'OAuth and TOTP verification required' USING ERRCODE = '42501';
    END IF;
    IF recovery.provider NOT IN ('google', 'twitter', 'x')
       OR (auth.jwt() -> 'app_metadata' ->> 'provider') IS DISTINCT FROM recovery.provider THEN
        RAISE EXCEPTION 'Recovery provider mismatch' USING ERRCODE = '42501';
    END IF;
    SELECT EXISTS (
        SELECT 1
        FROM jsonb_array_elements(COALESCE(auth.jwt() -> 'amr', '[]'::jsonb)) AS entry
        WHERE entry ->> 'method' = 'oauth'
          AND to_timestamp((entry ->> 'timestamp')::double precision)
              >= recovery.requested_at - interval '5 seconds'
    ) INTO has_recent_oauth;
    IF NOT has_recent_oauth THEN
        RAISE EXCEPTION 'Fresh OAuth authentication required' USING ERRCODE = '42501';
    END IF;

    UPDATE public.privacy_password_credentials
    SET password_hash = extensions.crypt(p_new_password, extensions.gen_salt('bf', 12)),
        failed_attempts = 0,
        locked_until = NULL,
        updated_at = timezone('utc'::text, now())
    WHERE profile_id = auth.uid();
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Privacy password not initialized' USING ERRCODE = '42501';
    END IF;
    DELETE FROM public.privacy_password_recovery_requests
    WHERE profile_id = auth.uid();
END;
$$;

