9. 年齢制限対象コンテンツ
Sharemariumでは、18歳未満の利用者を保護するため、成人向け書籍及びその関連投稿の表示を制限することがあります。
運営者は、書籍の題名、説明、画像、投稿内容、外部から提供された情報、利用者からの通報その他の事情を基に、年齢制限対象コンテンツを判定します。
判定方法及び基準の詳細は、表示制限の回避を防ぐため公開しないことがあります。
成人向け書籍に関する投稿
18歳以上の利用者は、適法に出版又は流通している成人向け書籍について、感想や批評を投稿できる場合があります。
ただし、次の内容は禁止します。
•	性行為等を必要以上に具体的又は露骨に描写すること
•	わいせつな画像、映像又は音声を投稿すること
•	性的な勧誘、出会い又は取引を目的とすること
•	児童を性的な対象として描写、賞賛又は正当化すること
•	児童の性的搾取又は虐待に関するコンテンツを投稿、共有又は入手しようとすること
•	違法に作成又は流通しているコンテンツを紹介又は共有すること
•	成人向けコンテンツを18歳未満の利用者へ見せることを目的とすること
表示制限の回避禁止
次の行為は禁止します。
•	虚偽の生年月日を登録すること
•	他人の年齢情報又はアカウントを利用すること
•	伏字、記号、異体字、隠語又は画像等を用いて判定を回避すること
•	成人向け書籍を別の書籍として登録すること
•	書籍名又は投稿内容を意図的に変えて表示制限を回避すること
年齢制限対象コンテンツが18歳未満の利用者に表示された場合は、通報機能又はお問い合わせ窓口から連絡してください。
