  static List<_GuidelinesBlock> _parseBlocks(String source) {
    final blocks = <_GuidelinesBlock>[];
    var nextLineIsSectionHeading = false;
    const labels = {'運営者', 'サービス名', 'お問い合わせ方法', '制定日', '最終改定日', 'バージョン'};

    for (final rawLine in source.split('\n')) {
      final line = rawLine.trim();
      if (line.isEmpty) {
        continue;
      }
      if (RegExp(r'^_+$').hasMatch(line)) {
        nextLineIsSectionHeading = true;
        continue;
      }

      if (blocks.isEmpty) {
        blocks.add(
          _GuidelinesBlock(text: line, style: _titleStyle, spacingBefore: 0),
        );
      } else if (nextLineIsSectionHeading) {
        nextLineIsSectionHeading = false;
        blocks.add(
          _GuidelinesBlock(text: line, style: _headingStyle, spacingBefore: 20),
        );
      } else if (labels.contains(line)) {
        blocks.add(
          _GuidelinesBlock(text: line, style: _labelStyle, spacingBefore: 10),
        );
      } else if (line.startsWith('•')) {
        blocks.add(
          _GuidelinesBlock(
            text: line,
            style: _bodyStyle,
            spacingBefore: 0,
            isBullet: true,
          ),
        );
      } else {
        blocks.add(
          _GuidelinesBlock(text: line, style: _bodyStyle, spacingBefore: 6),
        );
      }
    }

    return blocks;
  }
