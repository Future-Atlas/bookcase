10. 生成AIの利用
利用者は、レビューの構成整理、文章の校正、表現の提案その他の補助として、生成AIを利用できます。
ただし、生成AIを利用した場合も、投稿内容についての責任は投稿者本人が負います。
次の行為は禁止します。
•	書籍を読まず、生成AIだけでレビューを作成して投稿すること
•	生成AIが作成した架空の読書経験を、自分の経験として投稿すること
•	事実確認をせず、生成AIの回答をそのまま投稿すること
•	実在の人物が発言又は作成したと誤認させる内容を投稿すること
•	生成AIを利用して他人の文章を模倣又は無断複製すること
•	自動生成したレビュー、返信その他の投稿を大量又は反復して投稿すること
•	生成AIを利用して嫌がらせ、スパム又は不正な評価操作を行うこと
•	第三者の個人情報又は秘密情報を生成AIへ不適切に入力すること
運営者が、投稿の透明性又は不正利用防止のため合理的に必要と判断した場合、生成AIを利用した旨の表示を求めることがあります。
