8-1. 返信を利用するときのルール
返信は、対象となる投稿又は返信に関連する内容を、相手及び他の閲覧者に配慮して投稿してください。返信にも、本ガイドラインのすべての禁止事項が適用されます。
次の行為は禁止します。
•	対象となる投稿又は会話と無関係な内容を繰り返し送ること
•	侮辱、威圧、嫌がらせ、差別、性的な勧誘又は一方的な宣伝を目的として返信すること
•	ブロック、非公開設定又は返信機能の利用制限を、別のアカウントその他の方法で回避すること
•	ネタバレ表示が適用されない部分に重大なネタバレを記載し、表示制限を回避すること
•	他人の氏名、連絡先、非公開情報その他の個人情報を返信に記載すること
•	自動化された返信又は同一若しくは類似する返信を大量若しくは反復して投稿すること
返信を閲覧できることと、返信を投稿できることは異なります。返信ボタンに利用制限が表示される場合、その制限を回避して返信してはなりません。
鍵アカウントの投稿に対する返信は、対象投稿を閲覧できる者に限って表示されます。返信の内容を、対象投稿を閲覧する権限のない者へ無断で転載又は共有しないでください。
返信に問題がある場合は、対象返信に設置された報告機能から連絡できます。報告機能では対象を十分に特定できない場合又は権利侵害に関する申出は、お問い合わせ窓口から、対象となる返信を特定できる情報とともに連絡してください。
