次の行為は禁止します。
•	広告又は宣伝であることを隠すこと
•	利益を受けているにもかかわらず、完全に自発的な感想であるかのように表示すること
•	分かりにくい場所、表現又はハッシュタグで関係性を隠すこと
•	広告主等の指示に従い、不自然な高評価又は虚偽の評価を投稿すること
