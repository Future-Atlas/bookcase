import 'package:flutter/material.dart';

/// Public avatar images must belong to Sharemarium's own Supabase Storage
/// bucket. Never load arbitrary profile-provided URLs in other users' browsers.
/// This also protects historical rows that predate the database upload guard.
class AvatarUrlPolicy {
  static const allowedHosts = <String>{
    'jeyxadmkbzgpkveomesz.supabase.co', // production
    'wpoigmywpewrrbudqhgh.supabase.co', // staging
  };

  static final RegExp _profileId = RegExp(
    r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$',
    caseSensitive: false,
  );

  static final RegExp _filename = RegExp(r'^avatar[.](jpg|png|webp)$');

  /// Returns a canonical approved image URL or null (render initials/icon).
  /// Supplying ownerId additionally blocks referencing a different user's
  /// bucket path when that identity is available in the caller.
  static String? safeUrl(String? url, {String? ownerId}) {
    final input = url?.trim() ?? '';
    if (input.isEmpty) return null;
    final uri = Uri.tryParse(input);
    if (uri == null ||
        uri.scheme != 'https' ||
        !allowedHosts.contains(uri.host.toLowerCase()) ||
        uri.userInfo.isNotEmpty ||
        uri.hasPort ||
        uri.fragment.isNotEmpty) {
      return null;
    }
    final segments = uri.pathSegments;
    if (segments.length != 7 ||
        segments[0] != 'storage' ||
        segments[1] != 'v1' ||
        segments[2] != 'object' ||
        segments[3] != 'public' ||
        segments[4] != 'avatars' ||
        !_profileId.hasMatch(segments[5]) ||
        !_filename.hasMatch(segments[6])) {
      return null;
    }
    if (ownerId != null &&
        segments[5].toLowerCase() != ownerId.toLowerCase()) {
      return null;
    }
    // Reject encoded path tricks and query strings other than the image
    // cache-busting timestamp generated by the existing avatar uploader.
    final expectedPath =
        '/storage/v1/object/public/avatars/' + segments[5] + '/' + segments[6];
    if (uri.path != expectedPath ||
        (uri.hasQuery && !RegExp(r'^v=[0-9]{1,20}$').hasMatch(uri.query))) {
      return null;
    }
    return uri.toString();
  }

  static ImageProvider? image(String? url, {String? ownerId}) {
    final approved = safeUrl(url, ownerId: ownerId);
    return approved == null ? null : NetworkImage(approved);
  }
}
